def parse(text):
    chapters = []
    for chunk in re.split(r"\n(?=## )", text):
        if not chunk.startswith("## "):
            continue
        title, _, body = chunk.partition("\n")
        chapter = title[3:].strip()
        short = chapter.split("：", 1)[0]
        questions = []
        for qchunk in re.split(r"\n(?=### )", body):
            if not qchunk.startswith("### "):
                continue
            first, _, rest = qchunk.partition("\n")
            m = re.match(r"###\s+(\d+)\.\s*(.*)", first)
            if not m:
                continue
            num, question = m.group(1), m.group(2).strip()
            body_q = rest.strip()
            body_q = re.sub(r"\n---\s*$", "", body_q).strip()
            memo = ""
            mm = re.search(r"\*\*记忆要点：\*\*\s*(.*)", body_q)
            if mm:
                memo = mm.group(1).strip()
            questions.append(
                {
                    "num": num,
                    "question": question,
                    "body": body_q,
                    "memo": memo,
                    "short": short,
                    "chapter": chapter,
                }
            )
        chapters.append({"chapter": chapter, "short": short, "questions": questions})
    return chapters


