def build_concepts(chapters):
    nb = new_nb()
    nb.cells.append(md_cell(CONCEPTS, "concepts-body"))
    nb.cells.append(
        md_cell(
            "# 按题号回查的记忆要点\n\n下面每条都来自题目记录，题号与 `错题.ipynb` 一致。",
            "memo-intro",
        )
    )
    for ci, chapter in enumerate(chapters):
        lines = [f"## {chapter['chapter']}", ""]
        for q in chapter["questions"]:
            memo = q["memo"] or "见错题本解析。"
            lines.append(f"- **{q['short']} {q['num']}** {memo}")
        nb.cells.append(md_cell("\n".join(lines), f"memo-{ci}"))
    return nb


